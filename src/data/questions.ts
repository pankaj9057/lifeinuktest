function getQuestionsForSet(setIndex: number): Question[] {
  const total = questionBank.length;
  const setSize = 24;
  const result: Question[] = [];
  const used = new Set<string>();

  // Each set gets a different starting offset and spread
  const offsets = [0, 8, 16, 24, 32, 4, 12, 20, 28, 36, 3, 11, 19, 27, 7, 15, 23];
  const start = offsets[setIndex % offsets.length];

  // First pass — sequential from offset
  for (let i = 0; i < total && result.length < setSize; i++) {
    const idx = (start + i) % total;
    const q = questionBank[idx];
    if (!used.has(q.id)) {
      used.add(q.id);
      result.push(q);
    }
  }

  // Fill remaining if needed
  for (let i = 0; i < total && result.length < setSize; i++) {
    const q = questionBank[i];
    if (!used.has(q.id)) {
      used.add(q.id);
      result.push(q);
    }
  }

  return result.slice(0, setSize);
}

